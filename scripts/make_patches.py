"""Generate the skin-patch definitions (src/afscreen/face/patches_def.py).

    python scripts/make_patches.py reference_face.png
    python scripts/make_patches.py reference_face.png --preview docs/figures/patches.png

Each fine patch is a group of Face Mesh triangles. Triangles whose centre lies inside the
forehead / cheek polygons (on a frontal reference face) are clustered by position into
9 forehead and 8 + 8 cheek patches (25 in total). Coarser levels are unions of fine patches:
neighbouring fine patches are merged into 12, and those into 6 (2 per region), so traces are
only ever measured at the fine level and merged afterwards. Because patches are defined on the
mesh, they move and deform with the face in every video; the reference face is used only here.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import cv2
import numpy as np

from afscreen.face.tracker import FaceTracker

# Skin polygons as Face Mesh landmark indices; "right"/"left" are from the subject's point of
# view. They stay inside skin and avoid eyes, eyebrows, nostrils and lips.
REGIONS: dict[str, list[int]] = {
    "forehead": [67, 109, 10, 338, 297, 334, 296, 336, 9, 107, 66, 105],
    "right_cheek": [117, 118, 119, 100, 142, 203, 206, 207, 187, 123, 116],
    "left_cheek": [346, 347, 348, 329, 371, 423, 426, 427, 411, 352, 345],
}
FINE_PER_REGION = {"forehead": 9, "right_cheek": 8, "left_cheek": 8}
COARSE_PER_REGION = {12: 4, 6: 2}
OUT = Path(__file__).resolve().parents[1] / "src" / "afscreen" / "face" / "patches_def.py"


def mesh_triangles() -> np.ndarray:
    from mediapipe.tasks.python.vision import FaceLandmarksConnections as C

    edges = C.FACE_LANDMARKS_TESSELATION  # listed as triangles: 3 consecutive edges each
    tris = {tuple(sorted((edges[i].start, edges[i + 1].start, edges[i + 2].start))) for i in range(0, len(edges), 3)}
    return np.array(sorted(tris))


def kmeans_ordered(points: np.ndarray, k: int, weights: np.ndarray | None = None) -> np.ndarray:
    """Cluster labels 0..k-1, numbered top-to-bottom then left-to-right."""
    from sklearn.cluster import KMeans

    labels = KMeans(n_clusters=k, n_init=10, random_state=0).fit_predict(points, sample_weight=weights)
    centres = np.array([points[labels == c].mean(axis=0) for c in range(k)])
    row_h = np.ptp(points[:, 1]) / max(1, round(np.sqrt(k))) or 1.0
    order = sorted(range(k), key=lambda c: (round(centres[c, 1] / row_h), centres[c, 0]))
    remap = np.empty(k, dtype=int)
    remap[order] = np.arange(k)
    return remap[labels]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("face", help="frontal reference photo")
    ap.add_argument("--preview", help="save an image of the three patch levels here")
    args = ap.parse_args()

    img = cv2.imread(args.face)
    with FaceTracker(mode="image") as tracker:
        face = tracker.detect(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
    if face is None:
        raise SystemExit("no face found")
    pts = face.points[:, :2]
    tris = mesh_triangles()
    centres = pts[tris].mean(axis=1)

    fine: dict[str, list[list[int]]] = {}
    groups: dict[int, list[list[int]]] = {12: [], 6: []}
    for region, k in FINE_PER_REGION.items():
        mask = np.zeros(img.shape[:2], np.uint8)
        cv2.fillPoly(mask, [np.round(pts[REGIONS[region]]).astype(np.int32)], 1)
        cx, cy = np.round(centres).astype(int).T
        inside = mask[np.clip(cy, 0, mask.shape[0] - 1), np.clip(cx, 0, mask.shape[1] - 1)].astype(bool)
        region_tris, region_c = tris[inside], centres[inside]
        labels = kmeans_ordered(region_c, k)
        first = len(fine)
        fine_centres = []
        for c in range(k):
            fine[f"{region}_{c + 1}"] = region_tris[labels == c].tolist()
            fine_centres.append(region_c[labels == c].mean(axis=0))
        fine_centres = np.array(fine_centres)
        # 12 = 4 per region, from the fine patches; 6 = 2 per region, from the 12-level groups.
        g12 = kmeans_ordered(fine_centres, COARSE_PER_REGION[12])
        members12 = [[first + i for i in np.flatnonzero(g12 == g)] for g in range(COARSE_PER_REGION[12])]
        c12 = np.array([fine_centres[np.array(m) - first].mean(axis=0) for m in members12])
        g6 = kmeans_ordered(c12, COARSE_PER_REGION[6], weights=np.array([len(m) for m in members12], float))
        groups[12] += members12
        groups[6] += [sorted(sum((members12[i] for i in np.flatnonzero(g6 == g)), [])) for g in range(COARSE_PER_REGION[6])]

    lines = [
        '"""Skin patches. GENERATED by scripts/make_patches.py - do not edit."""',
        "",
        "# fine patch name -> Face Mesh triangles (3 landmark indices each)",
        "FINE_PATCHES: dict[str, list[tuple[int, int, int]]] = {",
    ]
    for name, ts in fine.items():
        lines.append(f"    {name!r}: [{', '.join(str(tuple(t)) for t in ts)}],")
    lines += ["}", "", "# coarser levels: each patch is a union of fine patches (indices into FINE_PATCHES)",
              "GROUPS: dict[int, list[list[int]]] = {"]
    for level, members in groups.items():
        lines.append(f"    {level}: {[list(map(int, m)) for m in members]},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sizes = [len(v) for v in fine.values()]
    print(f"{len(fine)} fine patches ({min(sizes)}-{max(sizes)} triangles each); levels 12 and 6 -> {OUT}")

    if args.preview:
        rng = np.random.default_rng(3)
        names = list(fine)
        (x0, y0), (x1, y1) = pts.min(0).astype(int), pts.max(0).astype(int)
        panels = []
        for level in (25, 12, 6):
            members = [[i] for i in range(len(names))] if level == 25 else groups[level]
            vis = img.copy()
            for m in members:
                color = tuple(int(c) for c in rng.integers(60, 255, 3))
                for i in m:
                    for t in fine[names[i]]:
                        cv2.fillPoly(vis, [np.round(pts[list(t)]).astype(np.int32)], color)
            vis = cv2.addWeighted(vis, 0.6, img, 0.4, 0)[max(0, y0 - 15): y1 + 15, max(0, x0 - 15): x1 + 15]
            vis = cv2.resize(vis, None, fx=2, fy=2, interpolation=cv2.INTER_CUBIC)
            cv2.putText(vis, f"{level} patches", (8, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2, cv2.LINE_AA)
            panels.append(vis)
        cv2.imwrite(args.preview, np.hstack(panels))


if __name__ == "__main__":
    main()
