"""Steps 2-3 - skin patches: per-patch colour, size and orientation in each frame.

Measurements are always taken on the 25 fine patches (patches_def.py, generated by
scripts/make_patches.py). Coarser levels (12, 6, and 1 = one region over all patches) are unions
of fine patches, so they are computed afterwards by pixel-weighted merging (:func:`merge`).
"""

from __future__ import annotations

import cv2
import numpy as np

from afscreen.config import SETTINGS
from afscreen.face.patches_def import FINE_PATCHES, GROUPS

PATCH_NAMES = tuple(FINE_PATCHES)
N_FINE = len(PATCH_NAMES)
LEVELS = (N_FINE, *sorted(GROUPS, reverse=True), 1)  # (25, 12, 6, 1)

_TRIS = np.array([t for name in PATCH_NAMES for t in FINE_PATCHES[name]], dtype=np.int64)  # (n_tri, 3)
_TRI_PATCH = np.array([i for i, name in enumerate(PATCH_NAMES) for _ in FINE_PATCHES[name]])
_VERTS = np.unique(_TRIS)


def level_members(level: int) -> list[list[int]]:
    """Fine-patch indices making up each patch of ``level``."""
    if level == N_FINE:
        return [[i] for i in range(N_FINE)]
    if level == 1:
        return [list(range(N_FINE))]
    return GROUPS[level]


def measure(frame: np.ndarray, points: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Mean RGB, pixel count and camera-facing score of every fine patch in one frame.

    ``points`` are the (478, 3) landmarks (x, y in pixels, z in the same scale).
    Returns rgb (P, 3) (NaN for empty patches), counts (P,), facing (P,): |cos| of the angle
    between each patch's surface normal and the camera axis (1 = facing the camera,
    0 = edge-on), area-weighted over its triangles.
    """
    h, w = frame.shape[:2]
    xy = points[:, :2]
    used = xy[_VERTS]
    x0, y0 = np.maximum(np.floor(used.min(axis=0)).astype(int), 0)
    x1, y1 = np.minimum(np.ceil(used.max(axis=0)).astype(int) + 1, [w, h])
    if x1 <= x0 or y1 <= y0:
        return np.full((N_FINE, 3), np.nan), np.zeros(N_FINE), np.full(N_FINE, np.nan)

    # Label image: pixel value = patch index + 1 (0 = in no patch); one bincount per channel.
    labels = np.zeros((y1 - y0, x1 - x0), dtype=np.int32)
    shifted = np.round(xy - [x0, y0]).astype(np.int32)
    for i, name in enumerate(PATCH_NAMES):
        cv2.fillPoly(labels, [shifted[list(t)] for t in FINE_PATCHES[name]], i + 1)
    flat = labels.ravel()
    crop = frame[y0:y1, x0:x1].reshape(-1, 3).astype(np.float64)
    counts = np.bincount(flat, minlength=N_FINE + 1)[1:].astype(np.float64)
    sums = np.stack([np.bincount(flat, weights=crop[:, c], minlength=N_FINE + 1)[1:] for c in range(3)], axis=1)
    with np.errstate(invalid="ignore", divide="ignore"):
        rgb = sums / counts[:, None]
    rgb[counts == 0] = np.nan

    a, b, c = (points[_TRIS[:, k]].astype(np.float64) for k in range(3))
    n = np.cross(b - a, c - a)
    area = np.linalg.norm(n, axis=1)
    cos = np.abs(n[:, 2]) / np.maximum(area, 1e-9)
    facing = np.bincount(_TRI_PATCH, weights=cos * area, minlength=N_FINE) / np.maximum(
        np.bincount(_TRI_PATCH, weights=area, minlength=N_FINE), 1e-9)
    return rgb, counts, facing


def merge(rgb: np.ndarray, counts: np.ndarray, facing: np.ndarray, level: int):
    """Merge fine-patch measurements (T, 25, ...) into ``level`` patches, weighting by pixel count.

    Returns rgb (T, L, 3), counts (T, L), facing (T, L).
    """
    members = level_members(level)
    t = rgb.shape[0]
    out_rgb, out_n, out_f = np.full((t, len(members), 3), np.nan), np.zeros((t, len(members))), np.full((t, len(members)), np.nan)
    w = np.where(np.isfinite(rgb).all(axis=2), counts, 0.0)
    for j, m in enumerate(members):
        wm = w[:, m]
        tot = wm.sum(axis=1)
        ok = tot > 0
        out_n[:, j] = tot
        out_rgb[ok, j] = np.einsum("tp,tpc->tc", wm[ok], np.nan_to_num(rgb[ok][:, m])) / tot[ok, None]
        out_f[ok, j] = (wm[ok] * np.nan_to_num(facing[ok][:, m])).sum(axis=1) / tot[ok]
    return out_rgb, out_n, out_f


def choose_level(counts: np.ndarray, min_pixels: float = SETTINGS.min_patch_pixels) -> int:
    """Finest level whose typical patch has at least ``min_pixels`` pixels.

    ``counts`` are fine-patch pixel counts (T, 25). The typical patch size of a level is the
    median over frames of the median patch size, so a few small patches do not decide it.
    """
    seen = counts[(counts > 0).any(axis=1)]
    if len(seen) == 0:
        return LEVELS[-2]
    for level in LEVELS[:-1]:
        sizes = np.stack([seen[:, m].sum(axis=1) for m in level_members(level)], axis=1)
        if np.median(np.median(sizes, axis=1)) >= min_pixels:
            return level
    return LEVELS[-2]  # the coarsest multi-patch level, even if small


def draw(frame_bgr: np.ndarray, points: np.ndarray, level: int = N_FINE, weights: np.ndarray | None = None) -> np.ndarray:
    """Overlay the patches of ``level``; with ``weights`` (L,) in [0, 1], colour from red (low trust) to green."""
    out, overlay = frame_bgr.copy(), frame_bgr.copy()
    xy = np.round(points[:, :2]).astype(np.int32)
    wmax = np.nanmax(weights) if weights is not None and np.nanmax(weights) > 0 else 1.0
    for j, m in enumerate(level_members(level)):
        polys = [xy[list(t)] for i in m for t in FINE_PATCHES[PATCH_NAMES[i]]]
        if weights is None:
            color = (255, 255, 255)
        else:
            wgt = float(np.clip(np.nan_to_num(weights[j]) / wmax, 0, 1))
            color = (0, int(255 * wgt), int(255 * (1 - wgt)))
        cv2.fillPoly(overlay, polys, color)
    return cv2.addWeighted(overlay, 0.45, out, 0.55, 0)
